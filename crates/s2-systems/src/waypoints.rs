//! The waypoints a builder walks between on a site.
//!
//! [`WaypointSet::ORIGINAL`] holds `S2.EXE`'s four sets, bytes `+0x15` to `+0x21` of each
//! type's entry in the per-nation building table at `0x1f7d78` (1152 bytes per set, 36 per
//! type; Gold has the same bytes at `0x1f8050`), in the order of the nation byte. Whoever starts a
//! game gives each player a set. [`WaypointSet::new`] builds other sets, for tests or mods.

use std::borrow::Cow;

use crate::building_types::{BUILDING_TYPES, BuildingKind};

/// Waypoints per building type.
pub const WAYPOINTS: usize = 6;

/// A site type's builder waypoints: pixel offsets from the building's screen position.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, serde::Serialize, serde::Deserialize)]
pub struct Waypoints {
    /// The waypoint a new builder heads for first (`+0x15`).
    pub first: u8,
    /// Horizontal offsets (`+0x16` to `+0x1b`).
    pub x: [i8; WAYPOINTS],
    /// Vertical offsets (`+0x1c` to `+0x21`).
    pub y: [i8; WAYPOINTS],
}

/// Builder waypoints for every building type, indexed by type.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct WaypointSet {
    rows: Cow<'static, [Waypoints]>,
}

/// Why a custom waypoint set was refused.
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
pub enum WaypointSetError {
    /// A type's first waypoint is not one of its six.
    #[error("building type {kind} starts at waypoint {first}, past {WAYPOINTS}")]
    First {
        /// The type.
        kind: usize,
        /// Its first waypoint.
        first: u8,
    },
}

impl WaypointSet {
    /// The four sets of `S2.EXE` (and Gold, which has the same bytes), by nation byte:
    /// Romans, Vikings, Japanese, Africans.
    pub const ORIGINAL: [Self; 4] = [
        Self {
            rows: Cow::Borrowed(&ROMAN),
        },
        Self {
            rows: Cow::Borrowed(&VIKING),
        },
        Self {
            rows: Cow::Borrowed(&JAPANESE),
        },
        Self {
            rows: Cow::Borrowed(&AFRICAN),
        },
    ];

    /// A custom set: `rows[t]` holds building type `t`'s waypoints.
    ///
    /// # Errors
    ///
    /// [`WaypointSetError::First`] when a type's first waypoint is past its six.
    pub fn new(rows: Vec<Waypoints>) -> Result<Self, WaypointSetError> {
        if let Some((kind, row)) = rows
            .iter()
            .enumerate()
            .find(|(_, row)| usize::from(row.first) >= WAYPOINTS)
        {
            return Err(WaypointSetError::First {
                kind,
                first: row.first,
            });
        }
        Ok(Self {
            rows: Cow::Owned(rows),
        })
    }

    /// Building type `kind`'s waypoints, or `None` past the set.
    #[must_use]
    pub fn get(&self, kind: BuildingKind) -> Option<&Waypoints> {
        self.rows.get(kind.index())
    }
}

impl Default for WaypointSet {
    fn default() -> Self {
        Self::ORIGINAL[0].clone()
    }
}

impl std::hash::Hash for WaypointSet {
    /// The set is input data, checked by the data hash a replay carries; the state hash leaves
    /// it out.
    fn hash<H: std::hash::Hasher>(&self, _state: &mut H) {}
}

const fn w(first: u8, x: [i8; WAYPOINTS], y: [i8; WAYPOINTS]) -> Waypoints {
    Waypoints { first, x, y }
}

